/* Constantes de round (Rcon) */
static const uint8_t rcon[11] = {
    0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
};

/* Contexto AES: 11 round keys de 16 bytes cada */
typedef struct { uint8_t rk[11][16]; } AES_CTX;

/* ---------------------------------------------------------------
 * Key Expansion
 * --------------------------------------------------------------- */
static void aes_key_expand(AES_CTX *ctx, const uint8_t *key)
{
    memcpy(ctx->rk[0], key, 16);

    for (int r = 1; r <= AES_ROUNDS; r++) {
        uint8_t *prev = ctx->rk[r - 1];
        uint8_t *curr = ctx->rk[r];

        /* RotWord + SubWord + Rcon na primeira palavra */
        curr[0]  = sbox[prev[13]] ^ rcon[r] ^ prev[0];
        curr[1]  = sbox[prev[14]]            ^ prev[1];
        curr[2]  = sbox[prev[15]]            ^ prev[2];
        curr[3]  = sbox[prev[12]]            ^ prev[3];

        /* Restantes três palavras */
        for (int i = 4; i < 16; i++)
            curr[i] = curr[i - 4] ^ prev[i];
    }
}

/* ---------------------------------------------------------------
 * Encriptação de um bloco (SubBytes + ShiftRows + MixColumns + ARK)
 * --------------------------------------------------------------- */
static inline uint8_t xtime(uint8_t x) { return xtime_table[x]; }
static inline uint8_t mul(uint8_t a, uint8_t b)
{
    /* multiplicação em GF(2^8) por 2 ou 3 apenas (suficiente p/ MixColumns) */
    return (b == 2) ? xtime(a) : (xtime(a) ^ a);
}

static void aes_encrypt_block(const AES_CTX *ctx,
                               const uint8_t *in, uint8_t *out)
{
    uint8_t s[16], t[16];

    /* AddRoundKey (round 0) */
    for (int i = 0; i < 16; i++)
        s[i] = in[i] ^ ctx->rk[0][i];

    for (int r = 1; r <= AES_ROUNDS; r++) {
        /* SubBytes */
        for (int i = 0; i < 16; i++)
            t[i] = sbox[s[i]];

        /* ShiftRows:
         *  row 0: sem shift    cols 0,4,8,12
         *  row 1: shift 1      cols 1,5,9,13
         *  row 2: shift 2      cols 2,6,10,14
         *  row 3: shift 3      cols 3,7,11,15
         */
        s[ 0]=t[ 0]; s[ 4]=t[ 4]; s[ 8]=t[ 8]; s[12]=t[12];
        s[ 1]=t[ 5]; s[ 5]=t[ 9]; s[ 9]=t[13]; s[13]=t[ 1];
        s[ 2]=t[10]; s[ 6]=t[14]; s[10]=t[ 2]; s[14]=t[ 6];
        s[ 3]=t[15]; s[ 7]=t[ 3]; s[11]=t[ 7]; s[15]=t[11];

        /* MixColumns (pulado no último round) */
        if (r < AES_ROUNDS) {
            for (int c = 0; c < 4; c++) {
                uint8_t a0=s[c*4], a1=s[c*4+1], a2=s[c*4+2], a3=s[c*4+3];
                t[c*4+0] = mul(a0,2)^mul(a1,3)^a2^a3;
                t[c*4+1] = a0^mul(a1,2)^mul(a2,3)^a3;
                t[c*4+2] = a0^a1^mul(a2,2)^mul(a3,3);
                t[c*4+3] = mul(a0,3)^a1^a2^mul(a3,2);
            }
            memcpy(s, t, 16);
        }

        /* AddRoundKey */
        for (int i = 0; i < 16; i++)
            s[i] ^= ctx->rk[r][i];
    }

    memcpy(out, s, 16);
}

/* ---------------------------------------------------------------
 * Encriptação ECB de buffer completo
 * --------------------------------------------------------------- */
static void aes_ecb_encrypt(const AES_CTX *ctx,
                             const uint8_t *in, uint8_t *out, size_t len)
{
    for (size_t i = 0; i < len; i += AES_BLOCK)
        aes_encrypt_block(ctx, in + i, out + i);
}

int main(void)
{
    uint8_t *plaintext  = malloc(MSG_SIZE);
    uint8_t *ciphertext = malloc(MSG_SIZE);
    uint8_t key[16] = {
        0x2b,0x7e,0x15,0x16,0x28,0xae,0xd2,0xa6,
        0xab,0xf7,0x15,0x88,0x09,0xcf,0x4f,0x3c
    };

    if (!plaintext || !ciphertext) {
        fprintf(stderr, "malloc failed\n");
        return 1;
    }

    srand(42);
    for (size_t i = 0; i < MSG_SIZE; i++)
        plaintext[i] = (uint8_t)(rand() & 0xff);

    /* Padding: garante múltiplo de 16 bytes (já é, mas por segurança) */
    if (MSG_SIZE % AES_BLOCK != 0) {
        fprintf(stderr, "MSG_SIZE deve ser múltiplo de %d\n", AES_BLOCK);
        return 1;
    }

    AES_CTX ctx;
    aes_key_expand(&ctx, key);

    /* --- vetor de teste FIPS-197 Appendix B --- */
    uint8_t test_in[16]  = {
        0x32,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,
        0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x34
    };
    uint8_t test_out[16];
    uint8_t expected[16] = {
        0x39,0x25,0x84,0x1d,0x02,0xdc,0x09,0xfb,
        0xdc,0x11,0x85,0x97,0x19,0x6a,0x0b,0x32
    };
    AES_CTX test_ctx;
    uint8_t test_key[16] = {
        0x2b,0x7e,0x15,0x16,0x28,0xae,0xd2,0xa6,
        0xab,0xf7,0x15,0x88,0x09,0xcf,0x4f,0x3c
    };
    aes_key_expand(&test_ctx, test_key);
    aes_encrypt_block(&test_ctx, test_in, test_out);

    printf("=== AES-128 ECB Benchmark ===\n");
    printf("Mensagem: %d MB | Chave: 128 bits | Rounds: %d | Runs: %d\n\n",
           MSG_SIZE >> 20, AES_ROUNDS, BENCH_RUNS);

    if (memcmp(test_out, expected, 16) == 0)
        printf("  Vetor FIPS-197: OK\n\n");
    else {
        printf("  Vetor FIPS-197: FALHOU — implementação incorreta!\n");
        return 1;
    }

    struct timespec t0, t1;
    double total_ns = 0.0;

    for (int r = 0; r < BENCH_RUNS; r++) {
        clock_gettime(CLOCK_MONOTONIC, &t0);
        aes_ecb_encrypt(&ctx, plaintext, ciphertext, MSG_SIZE);
        clock_gettime(CLOCK_MONOTONIC, &t1);

        double ns = (t1.tv_sec - t0.tv_sec) * 1e9 +
                    (t1.tv_nsec - t0.tv_nsec);
        total_ns += ns;
        printf("  Run %2d: %.2f ms\n", r + 1, ns / 1e6);
    }

    double avg_ms     = total_ns / BENCH_RUNS / 1e6;
    double throughput = (MSG_SIZE / (1024.0 * 1024.0)) / (avg_ms / 1000.0);

    printf("\n  Média:      %.2f ms\n", avg_ms);
    printf("  Throughput: %.1f MB/s\n", throughput);

    free(plaintext);
    free(ciphertext);
    return 0;
}
